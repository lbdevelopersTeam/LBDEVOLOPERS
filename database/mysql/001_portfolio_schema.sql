-- ============================
-- site_settings
-- ============================
CREATE TABLE site_settings (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    setting_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    setting_value TEXT NULL,
    value_type ENUM('string', 'text', 'url', 'boolean', 'integer', 'json') NOT NULL DEFAULT 'string',
    is_public BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'False values may be returned only to authenticated administrators.',
    description VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_site_settings_key (setting_key),
    KEY idx_site_settings_public (is_public, deleted_at, setting_key),
    CONSTRAINT chk_site_settings_key CHECK (setting_key REGEXP '^[a-z][a-z0-9_]*$'),
    CONSTRAINT chk_site_settings_typed_value CHECK (
        setting_value IS NULL
        OR (
            (value_type <> 'boolean' OR setting_value IN ('true', 'false'))
            AND (value_type <> 'integer' OR setting_value REGEXP '^-?[0-9]+$')
            AND (value_type <> 'json' OR JSON_VALID(setting_value))
        )
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Typed key-value content configuration. Secrets must remain in environment variables, never here.';

