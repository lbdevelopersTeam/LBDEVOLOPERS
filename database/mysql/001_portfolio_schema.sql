  COMMENT='Ordered project galleries. Hard project deletion cascades to dependent image metadata.';

-- ============================
-- skills
-- ============================
CREATE TABLE skills (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(120) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    category ENUM('frontend', 'backend', 'database', 'devops', 'tools', 'soft-skill') NOT NULL,
    proficiency_level TINYINT UNSIGNED NOT NULL,
    icon_url VARCHAR(2048) NULL,
    sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_skills_name (name),
    UNIQUE KEY uq_skills_slug (slug),
    KEY idx_skills_category_order (category, deleted_at, sort_order, name),
    KEY idx_skills_featured (is_featured, deleted_at, sort_order),
    CONSTRAINT chk_skills_proficiency CHECK (proficiency_level BETWEEN 1 AND 100),
    CONSTRAINT chk_skills_slug CHECK (slug REGEXP '^[a-z0-9]+(-[a-z0-9]+)*$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Curated technical and interpersonal skills; categories are a small, fixed presentation taxonomy.';

-- ============================
-- project_skills
