-- LB Developers portfolio reference schema
-- Target: Oracle MySQL 8.0.16+ (the first 8.0 release that enforces CHECK constraints)
-- Run this file against an empty, already-provisioned database.
-- Application connections must set their session time zone to UTC.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;
SET SESSION time_zone = '+00:00';

-- ============================
-- project_categories
-- ============================
CREATE TABLE project_categories (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(80) NOT NULL,
    slug VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    description VARCHAR(500) NULL,
    sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_project_categories_name (name),
    UNIQUE KEY uq_project_categories_slug (slug),
    KEY idx_project_categories_public (is_active, deleted_at, sort_order, name),
    CONSTRAINT chk_project_categories_slug CHECK (slug REGEXP '^[a-z0-9]+(-[a-z0-9]+)*$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Reusable project categories; soft deletion preserves historical classification.';

-- ============================
-- users
-- ============================
CREATE TABLE users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Argon2id or bcrypt hash generated by the application; never plaintext.',
    role ENUM('owner', 'admin', 'editor') NOT NULL DEFAULT 'owner',
    avatar_url VARCHAR(2048) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_email (email),
    KEY idx_users_role (role, is_active, deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Private dashboard identities; designed for one owner but safely supports delegated editors.';

-- ============================
-- user_sessions
-- ============================
CREATE TABLE user_sessions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NOT NULL,
    token_hash BINARY(32) NOT NULL COMMENT 'SHA-256 digest of the random session token; the raw token is never stored.',
    ip_hash BINARY(32) NULL COMMENT 'Optional keyed hash used for anomaly detection without retaining the raw IP.',
    user_agent VARCHAR(512) NULL,
    last_seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at DATETIME NOT NULL,
    revoked_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_user_sessions_token_hash (token_hash),
    KEY idx_user_sessions_user_active (user_id, revoked_at, expires_at),
    KEY idx_user_sessions_expiry (expires_at, revoked_at),
    CONSTRAINT fk_user_sessions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_user_sessions_expiry CHECK (expires_at > created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Revocable server-side admin sessions. User deletion cascades because a session has no independent value.';

-- ============================
-- projects
-- ============================
CREATE TABLE projects (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    category_id BIGINT UNSIGNED NOT NULL,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    title VARCHAR(160) NOT NULL,
    slug VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    short_description VARCHAR(500) NOT NULL,
    full_description MEDIUMTEXT NOT NULL,
    thumbnail_url VARCHAR(2048) NULL,
    cover_image_url VARCHAR(2048) NULL,
    live_url VARCHAR(2048) NULL,
    repo_url VARCHAR(2048) NULL,
    status ENUM('draft', 'published', 'archived') NOT NULL DEFAULT 'draft',
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    view_count BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Cached lifetime total; page_views remains the analytical source.',
    sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    published_at DATETIME NULL,
    meta_title VARCHAR(60) NULL,
    meta_description VARCHAR(160) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_projects_slug (slug),
    KEY idx_projects_public_featured (status, is_featured, deleted_at, sort_order, id),
    KEY idx_projects_category_public (category_id, status, deleted_at, sort_order, id),
    KEY idx_projects_published (status, deleted_at, published_at, id),
    KEY idx_projects_created_by (created_by),
    KEY idx_projects_updated_by (updated_by),
    FULLTEXT KEY ft_projects_search (title, short_description, full_description),
    CONSTRAINT fk_projects_category FOREIGN KEY (category_id) REFERENCES project_categories(id) ON DELETE RESTRICT,
    CONSTRAINT fk_projects_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_projects_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_projects_slug CHECK (slug REGEXP '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT chk_projects_publish_state CHECK (status <> 'published' OR published_at IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Portfolio projects. Categories are normalized because their values evolve over time.';

-- ============================
-- project_images
